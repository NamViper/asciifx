#!/usr/bin/env python3
"""Generate ``src/asciifx/sources/glyph_masks.py``: ink-coverage masks of the ASCII glyphs.

Each printable ASCII character (0x20-0x7E) is rendered into one terminal cell
(advance width x ascent+descent, the box a terminal gives it) with a monospace
font at a large size, then area-averaged down to MASK_W x MASK_H samples. A
sample is the fraction of that part of the cell covered by ink, stored as one
hex digit (0 = empty, f = fully covered).

Run once from the repo root and commit the output; nothing calls this at runtime:

    .venv/bin/python tools/gen_glyph_masks.py [--size 5x10] [--font PATH]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

FONTS = (
    "/mnt/c/Windows/Fonts/CascadiaMono.ttf",  # Windows Terminal's default font
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
)
OUT = Path(__file__).resolve().parent.parent / "src" / "asciifx" / "sources" / "glyph_masks.py"
CHARS = "".join(chr(c) for c in range(0x20, 0x7F))
LEVELS = 15  # one hex digit per sample
RENDER_EM = 1024  # font size in pixels for the high-resolution render


def pick_font(path: str | None) -> str:
    if path:
        return path
    for candidate in FONTS:
        if Path(candidate).is_file():
            return candidate
    raise SystemExit(f"none of these fonts exist: {', '.join(FONTS)}; pass --font")


def coverage(font: ImageFont.FreeTypeFont, ch: str, mask_w: int, mask_h: int) -> np.ndarray:
    """Ink coverage 0..1 of ``ch`` over its cell, area-averaged to mask_h x mask_w."""
    ascent, descent = font.getmetrics()
    cell = Image.new("L", (round(font.getlength("M")), ascent + descent), 0)
    ImageDraw.Draw(cell).text((0, ascent), ch, font=font, fill=255, anchor="ls")
    small = cell.resize((mask_w, mask_h), Image.Resampling.BOX)  # exact area average
    return np.asarray(small, np.float64) / 255.0


def encode(cov: np.ndarray) -> str:
    """Rows of hex digits separated by spaces, e.g. '0880 0880 ...' for '|'."""
    q = np.rint(cov * LEVELS).astype(int)
    return " ".join("".join(f"{v:x}" for v in row) for row in q)


def render_module(font_path: str, mask_w: int, mask_h: int) -> str:
    font = ImageFont.truetype(font_path, RENDER_EM)
    family, style = font.getname()
    ascent, descent = font.getmetrics()
    advance = font.getlength("M")
    lines = [
        '"""Ink-coverage masks of the printable ASCII glyphs, for shape-matching image conversion.',
        "",
        "GENERATED by tools/gen_glyph_masks.py; do not edit by hand. Plain data, so it",
        "imports without numpy or Pillow.",
        "",
        "Each mask is MASK_H rows of MASK_W samples over one terminal cell, top to",
        "bottom, rows separated by spaces. A sample is one hex digit: the fraction of",
        "that part of the cell covered by ink, times LEVELS (0 = empty, f = solid).",
        '"""',
        "",
        f"FONT = {f'{family} {style}'!r}",
        f"FONT_FILE = {Path(font_path).name!r}",
        f"CELL_ASPECT = {(ascent + descent) / advance:.3f}  # glyph cell height / width in this font",
        f"MASK_W, MASK_H = {mask_w}, {mask_h}",
        f"LEVELS = {LEVELS}",
        "",
        "MASKS: dict[str, str] = {",
    ]
    for ch in CHARS:
        lines.append(f"    {ch!r}: {encode(coverage(font, ch, mask_w, mask_h))!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--font", help="TrueType font (default: Cascadia Mono, else DejaVu Sans Mono)")
    parser.add_argument("--size", default="5x10", help="mask size WxH (default 5x10)")
    parser.add_argument("--out", type=Path, default=OUT, help=f"output file (default {OUT})")
    args = parser.parse_args()
    mask_w, mask_h = (int(v) for v in args.size.lower().split("x"))
    font_path = pick_font(args.font)
    args.out.write_text(render_module(font_path, mask_w, mask_h))
    print(f"wrote {args.out} ({len(CHARS)} glyphs, {mask_w}x{mask_h}, {Path(font_path).name})")


if __name__ == "__main__":
    main()
